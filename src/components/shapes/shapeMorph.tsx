"use client";

import { useEffect, useRef } from "react";
import { animate, type AnimationPlaybackControls } from "motion/react";
import { MORPH_PAIRS } from "./morphData";

const MORPH_TURN = 90;

const TEMPOS = {
  /** Holds each shape, then springs to the next. */
  gentle: { holdMs: 1600, spinMs: 0, stiffness: 90, damping: 11 },
  /** The Material loading indicator: always spinning, always morphing. */
  loader: { holdMs: 350, spinMs: 4666, stiffness: 200, damping: 17 },
  /** The same motion, slowed down for large background shapes. */
  ambient: { holdMs: 900, spinMs: 40000, stiffness: 40, damping: 7 },
};

function interpolatePath(
  from: readonly number[],
  to: readonly number[],
  t: number,
) {
  let d = "";
  for (let i = 0; i < from.length; i++) {
    const value = from[i] + (to[i] - from[i]) * t;
    d += `${i === 0 ? "M" : i === 2 ? "C" : " "}${Math.round(value * 100) / 100}`;
  }
  return `${d}Z`;
}

type ShapeMorphProps = {
  /** Which shape in the sequence to begin on. */
  startAt?: number;
  tempo?: keyof typeof TEMPOS;
  /** Overrides how long the tempo holds each shape. */
  holdMs?: number;
  className?: string;
};

/**
 * Loops through shapes generated by the expressive-shapes library
 * (see scripts/generate-shapes.py). Colored with currentColor.
 */
export function ShapeMorph({
  startAt = 0,
  tempo = "gentle",
  holdMs,
  className,
}: ShapeMorphProps) {
  const pathRef = useRef<SVGPathElement>(null);
  const first = startAt % MORPH_PAIRS.length;
  const { spinMs, stiffness, damping, holdMs: tempoHoldMs } = TEMPOS[tempo];
  const hold = holdMs ?? tempoHoldMs;

  useEffect(() => {
    const path = pathRef.current;
    if (!path || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      return;
    }

    let index = first;
    let angle = 0;
    let visible = true;
    let timer: ReturnType<typeof setTimeout>;
    let controls: AnimationPlaybackControls | undefined;

    const observer = new IntersectionObserver(([entry]) => {
      visible = entry.isIntersecting;
    });
    if (path.ownerSVGElement) observer.observe(path.ownerSVGElement);

    const morph = () => {
      if (!visible) {
        timer = setTimeout(morph, 250);
        return;
      }
      const [from, to] = MORPH_PAIRS[index];
      controls = animate(0, 1, {
        type: "spring",
        stiffness,
        damping,
        onUpdate: (t) => {
          path.setAttribute("d", interpolatePath(from, to, t));
          path.setAttribute("transform", `rotate(${angle + t * MORPH_TURN} 50 50)`);
        },
        onComplete: () => {
          index = (index + 1) % MORPH_PAIRS.length;
          angle = (angle + MORPH_TURN) % 360;
          timer = setTimeout(morph, hold);
        },
      });
    };

    timer = setTimeout(morph, hold);
    return () => {
      clearTimeout(timer);
      controls?.stop();
      observer.disconnect();
    };
  }, [first, hold, stiffness, damping]);

  return (
    <svg
      viewBox="0 0 100 100"
      aria-hidden="true"
      className={`overflow-visible fill-current ${className ?? ""}`}
      style={
        spinMs ? { animation: `shape-spin ${spinMs}ms linear infinite` } : undefined
      }
    >
      <path
        ref={pathRef}
        d={interpolatePath(MORPH_PAIRS[first][0], MORPH_PAIRS[first][1], 0)}
      />
    </svg>
  );
}
