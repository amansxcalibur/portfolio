#!/usr/bin/env python3
"""Generate the morph data behind <ShapeMorph /> using the expressive-shapes library.

    pip install expressive-shapes==0.2.0
    python scripts/generate-shapes.py

Writes src/components/shapes/morphData.ts and src/app/icon.svg.
"""
from pathlib import Path

from expressive_shapes import RoundedPolygon
from expressive_shapes.morph.bezier_morph import Morph
from expressive_shapes.shapes import shape_presets as presets

# Played in order, then looping back to the first. Follows the Material loader.
SEQUENCE = [
    "square",
    "slanted",
    "oval",
    "gem",
    "pentagon",
    "very_sunny",
    "cookie_12",
    "leaf_clover_4",
]
ROOT = Path(__file__).resolve().parent.parent


def to_polygon(preset):
    vertices, rounding = [], []
    for (x, y), corner in preset:
        vertices += [x, y]
        rounding.append(corner)
    return RoundedPolygon.create(vertices=vertices, per_vertex_rounding=rounding)


def flatten(curves):
    """[x0, y0, then x1, y1, x2, y2, x3, y3 per cubic] in a 0-100 box."""
    points = [curves[0].p0]
    for curve in curves:
        points += [curve.p1, curve.p2, curve.p3]
    return [round(v * 100, 1) for point in points for v in (point.x, point.y)]


def to_svg_path(values):
    start, rest = values[:2], values[2:]
    return f"M{start[0]} {start[1]}C" + " ".join(map(str, rest)) + "Z"


pairs = []
for name_a, name_b in zip(SEQUENCE, SEQUENCE[1:] + SEQUENCE[:1]):
    matched = Morph.match(
        to_polygon(getattr(presets, name_a)), to_polygon(getattr(presets, name_b))
    )
    pairs.append(
        (
            flatten(Morph.as_cubics(matched, progress=0.0)),
            flatten(Morph.as_cubics(matched, progress=1.0)),
        )
    )

body = ",\n".join(f"  [{a},\n   {b}]".replace(", ", ",") for a, b in pairs)
(ROOT / "src/components/shapes/morphData.ts").write_text(
    "// Generated by scripts/generate-shapes.py. Do not edit by hand.\n"
    f"// Sequence: {' -> '.join(SEQUENCE)} -> {SEQUENCE[0]}\n"
    "export const MORPH_PAIRS: ReadonlyArray<\n"
    "  readonly [readonly number[], readonly number[]]\n"
    f"> = [\n{body},\n];\n"
)

diamond = flatten(to_polygon(presets.puffy_diamond).get_all_curves())
(ROOT / "src/app/icon.svg").write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">'
    '<circle cx="50" cy="50" r="50" fill="#a6f0cb"/>'
    f'<path fill="#004d36" transform="translate(14 14) scale(.72)" d="{to_svg_path(diamond)}"/>'
    "</svg>\n"
)
